#!/usr/bin/env bash
# Update the website's generated static artifact from the RAYMOSAIC source repo.
# Usage: bash scripts/sync-raymosaic.sh /path/to/raymosaic
# Run in a development checkout, commit the resulting website changes separately.
set -euo pipefail
site="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source_repo="${1:-$(dirname "$site")/raymosaic}"
source_repo="$(cd "$source_repo" && pwd)"
test -f "$source_repo/src/optics.mjs" || { echo "Not a RAYMOSAIC source checkout: $source_repo" >&2; exit 1; }
dest="$site/lab/raymosaic"
files=(
  index.html styles.css LICENSE src/main.js src/optics.mjs src/scene.js
  src/targets.js src/gif-worker.js src/project-state.js src/i18n.js
  examples/raymosaic-heart.webp examples/raymosaic-nebu.webp
  examples/raymosaic-nebu.gif examples/raymosaic-scene-nebu.gif
)
for path in "${files[@]}"; do
  install -d "$(dirname "$dest/$path")"
  cp "$source_repo/$path" "$dest/$path"
done
install -d "$site/de/lab/raymosaic"
python3 - "$dest/index.html" "$site/de/lab/raymosaic/index.html" <<'PY'
from pathlib import Path
import sys
page = Path(sys.argv[1]).read_text(encoding="utf-8")
page = page.replace('<html lang="en">', '<html lang="de">')
page = page.replace('href="./styles.css"', 'href="/lab/raymosaic/styles.css"')
page = page.replace('src="./src/main.js"', 'src="/lab/raymosaic/src/main.js"')
page = page.replace('rel="canonical" href="https://www.dennishilk.com/lab/raymosaic/"',
                    'rel="canonical" href="https://www.dennishilk.com/de/lab/raymosaic/"')
page = page.replace('<title>RAYMOSAIC — Draw with reflected light</title>',
                    '<title>RAYMOSAIC — Zeichne mit reflektiertem Licht</title>')
page = page.replace('Make pictures from simulated reflections in hundreds of tiny mirrors. Draw, experiment with optics, and export an animated GIF — entirely in your browser.',
                    'Schreibe Namen und zeichne Motive aus reflektiertem Licht mit 448 Spiegeln. GIF, PNG, lokales Speichern und Teilen direkt im Browser.')
page = page.replace('content="en_US"', 'content="de_DE"')
page = page.replace('content="de_DE"', 'content="en_US"', 1) if False else page
Path(sys.argv[2]).write_text(page, encoding="utf-8")
PY
printf 'Source: dennishilk/raymosaic\nCommit: %s\nGenerated by: scripts/sync-raymosaic.sh\n' "$(git -C "$source_repo" rev-parse HEAD)" > "$dest/BUILD-SOURCE.txt"
echo "RAYMOSAIC synced into $dest (English + German). Nothing deployed."
