// Deterministic, network-free Blob Worker bundle. No bundler dependency.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const base=new URL('../assets/password-cracking-lab/',import.meta.url),check=process.argv.includes('--check');
const shader=readFileSync(new URL('sha256.wgsl',base),'utf8');
const shaderSource='// Generated by scripts/build-password-cracking-worker.mjs\nexport const SHADER_SOURCE='+JSON.stringify(shader)+';\n';
const modules=['wordlists-data.js','dictionary.js','sha256.js','search.js','gpu.js','worker.js'].map(name=>readFileSync(new URL(name,base),'utf8').replace(/^import .*;\s*$/gm,'').replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm,'').replace(/^export /gm,''));
const worker='const SHADER_SOURCE='+JSON.stringify(shader)+';\n'+modules.join('\n');
const workerSource='// Generated by scripts/build-password-cracking-worker.mjs\nexport const WORKER_SOURCE='+JSON.stringify(worker)+';\n';
for(const [name,source] of [['shader-source.js',shaderSource],['worker-source.js',workerSource]]){
  const file=new URL(name,base);if(check){if(readFileSync(file,'utf8')!==source)throw new Error('Outdated '+fileURLToPath(file));}
  else writeFileSync(file,source);
}
console.log(check?'Password-cracking bundles are current':'Password-cracking bundles built');
